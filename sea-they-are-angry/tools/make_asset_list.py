#!/usr/bin/env python3
"""Writes docs/ASSET_LIST.md from what's actually in the project, so it can't drift.
   python3 tools/make_asset_list.py            (from sea-they-are-angry/)
Models and textures come from art/, music from audio/, and the sound effects from
autoload/audio.gd's SOUNDS table (synthesised in code; a recording dropped at
res://audio/<key>.ogg takes its place)."""
import os, re, json, struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def size(p):
    n = os.path.getsize(p)
    return "%.1f MB" % (n / 1e6) if n > 1e6 else "%d KB" % max(1, round(n / 1e3))

def tris(path):
    # Triangles in a .glb, from its accessors (indices where there are any).
    try:
        with open(path, "rb") as f:
            f.read(12)
            clen, ctype = struct.unpack("<II", f.read(8))
            doc = json.loads(f.read(clen))
        total = 0
        for m in doc.get("meshes", []):
            for pr in m["primitives"]:
                a = doc["accessors"][pr["indices"] if "indices" in pr else pr["attributes"]["POSITION"]]
                total += a["count"] // 3 if "indices" in pr else a["count"] // 3
        return total, [a["name"] for a in doc.get("animations", [])]
    except Exception:
        return None, []

def rel(p):
    return os.path.relpath(p, ROOT).replace(os.sep, "/")

out = []
out.append("# Asset list\n")
out.append("Generated by `tools/make_asset_list.py` from the files in the project: run it again after changing `art/` or `audio/`.\n")
out.append("**Orientation and scale:** models face -Z (Godot's forward), the origin is at the feet, 1 unit is 1 metre. Characters are rigged GLBs made by `art/source/characters/build_characters.py` and animated by `animate.py` (Blender 4.2); `scenes/util/character_rig.gd` plays their clips.\n")

out.append("## Models\n")
out.append("| File | Size | Triangles | Animation clips |\n|---|---|---|---|")
for d in ("art/characters", "art/props", "art/environment"):
    full = os.path.join(ROOT, d)
    for fn in sorted(os.listdir(full)):
        if fn.endswith(".glb"):
            p = os.path.join(full, fn)
            t, clips = tris(p)
            sidecar = os.path.join(full, fn.replace(".glb", ".anims.json"))
            if not clips and os.path.exists(sidecar):
                try:
                    clips = sorted(json.load(open(sidecar)).keys())
                except Exception:
                    pass
            out.append("| `%s` | %s | %s | %s |" % (rel(p), size(p), t if t is not None else "?", ", ".join(clips) if clips else ""))
out.append("")

out.append("## Textures\n")
out.append("| File | Size |\n|---|---|")
tdir = os.path.join(ROOT, "art/textures")
for fn in sorted(os.listdir(tdir)):
    if fn.endswith(".png"):
        out.append("| `art/textures/%s` | %s |" % (fn, size(os.path.join(tdir, fn))))
out.append("")

out.append("## Music\n")
out.append("Made offline by `art/source/music/build_music.py` (numpy synthesis, ffmpeg to Ogg Vorbis), stored with Git LFS. `autoload/audio.gd` (`MUSIC`) crossfades them with the day.\n")
out.append("| File | Size |\n|---|---|")
adir = os.path.join(ROOT, "audio")
for fn in sorted(os.listdir(adir)):
    if fn.endswith(".ogg") and fn.startswith("music_"):
        out.append("| `audio/%s` | %s |" % (fn, size(os.path.join(adir, fn))))
out.append("")

out.append("## Recorded sounds\n")
out.append("CC0 or public-domain recordings that stand in for the made sound of the same key. Where each came from, and its licence, is in `docs/SOUND_CREDITS.md`.\n")
out.append("| File | Size |\n|---|---|")
for fn in sorted(os.listdir(adir)):
    if fn.endswith(".ogg") and not fn.startswith("music_"):
        out.append("| `audio/%s` | %s |" % (fn, size(os.path.join(adir, fn))))
out.append("")

out.append("## Sound effects\n")
out.append("Synthesised in code (`autoload/audio.gd`, cached in `user://`), unless a recording at `res://audio/<key>.ogg` stands in (add its row to `docs/SOUND_CREDITS.md` first).\n")
src = open(os.path.join(ROOT, "autoload/audio.gd")).read()
m = re.search(r"const SOUNDS := \{(.*?)\n\}", src, re.S)
keys = re.findall(r'"([a-z0-9_]+)":\s*\["(_s_[a-z0-9_]+)",\s*(true|false)\]', m.group(1)) if m else []
out.append("| Key | Loops |\n|---|---|")
for k, _fn, loops in keys:
    over = os.path.exists(os.path.join(adir, k + ".ogg"))
    out.append("| `%s` | %s%s |" % (k, "yes" if loops == "true" else "no", " (recording present)" if over else ""))
out.append("")
out.append("%d sound effects (%d of them recordings), %d models, %d textures, %d pieces of music." % (
    len(keys),
    sum(1 for f in os.listdir(adir) if f.endswith(".ogg") and not f.startswith("music_")),
    sum(1 for d in ("art/characters","art/props","art/environment") for f in os.listdir(os.path.join(ROOT, d)) if f.endswith(".glb")),
    sum(1 for f in os.listdir(tdir) if f.endswith(".png")),
    sum(1 for f in os.listdir(adir) if f.endswith(".ogg") and f.startswith("music_")),
))
open(os.path.join(ROOT, "docs/ASSET_LIST.md"), "w").write("\n".join(out) + "\n")
print("wrote docs/ASSET_LIST.md")
